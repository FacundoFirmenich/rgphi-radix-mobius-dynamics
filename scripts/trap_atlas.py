#!/usr/bin/env python3
"""Exact finite-trap atlas for the RGΦ rational T/S graph.

The atlas enumerates all reduced nonterminal states 0<a<b with b<=D, builds
all admissible T/S transitions, computes SCCs, closed SCCs modulo the proved
terminal set, and finite forward-invariant closures whose outgoing nonterminal
edges remain inside the denominator bound.
"""
from __future__ import annotations
from fractions import Fraction
from math import gcd
from pathlib import Path
import csv, json
import networkx as nx

BASE=10
D=500
OUTDIR=Path(__file__).resolve().parent

TERMINAL={
    Fraction(2,11),Fraction(9,11),Fraction(0,1),Fraction(1,1),
    Fraction(1,2),Fraction(1,3),Fraction(2,3),Fraction(3,4),
    Fraction(4,5),Fraction(5,6),Fraction(7,8),Fraction(7,9),
    Fraction(7,10),Fraction(4,11),Fraction(7,11),Fraction(7,12),
    Fraction(2,13),Fraction(5,13),Fraction(6,13),Fraction(7,13),
    Fraction(8,13),Fraction(11,13),Fraction(11,20)
}


def T(x: Fraction):
    y=BASE*x
    return y-(y.numerator//y.denominator)


def S(x: Fraction):
    if x==0 or 2*x<1:
        return None
    u=1/x-1
    y=BASE*u
    return 1/(1+y-(y.numerator//y.denominator))


def children(x):
    out=[("T",T(x))]
    sx=S(x)
    if sx is not None:
        out.append(("S",sx))
    return out


def multiplicative_order(a,n):
    if gcd(a,n)!=1:
        return None
    x=1
    for k in range(1,10*n+1):
        x=(x*a)%n
        if x==1:
            return k
    raise RuntimeError((a,n))


def main():
    states=[]
    for b in range(2,D+1):
        for a in range(1,b):
            if gcd(a,b)==1:
                x=Fraction(a,b)
                if x not in TERMINAL:
                    states.append(x)
    state_set=set(states)

    G=nx.DiGraph()
    G.add_nodes_from(states)
    outside={x:[] for x in states}
    terminal_edges={x:[] for x in states}
    edge_action={}

    for x in states:
        for act,y in children(x):
            if y in TERMINAL:
                terminal_edges[x].append((act,y))
            elif y in state_set:
                G.add_edge(x,y)
                edge_action.setdefault((x,y),[]).append(act)
            else:
                outside[x].append((act,y))

    sccs=list(nx.strongly_connected_components(G))
    node_to_scc={x:i for i,C in enumerate(sccs) for x in C}
    cond=nx.DiGraph()
    cond.add_nodes_from(range(len(sccs)))
    unsafe_scc=set()
    for x in states:
        i=node_to_scc[x]
        if outside[x]:
            unsafe_scc.add(i)
        for y in G.successors(x):
            j=node_to_scc[y]
            if i!=j:
                cond.add_edge(i,j)

    closed_scc=[]
    for i,C in enumerate(sccs):
        if i in unsafe_scc:
            continue
        if all(j==i for j in cond.successors(i)):
            closed_scc.append(i)

    # Unique exact finite forward closures generated by SCCs.
    closure_map={}
    for i in cond.nodes:
        reachable={i}|nx.descendants(cond,i)
        if any(j in unsafe_scc for j in reachable):
            continue
        C=frozenset(x for j in reachable for x in sccs[j])
        closure_map.setdefault(C,[]).append(i)

    closures=sorted(closure_map,key=lambda C:(len(C),sorted((x.denominator,x.numerator) for x in C)))
    small_closures=[C for C in closures if len(C)<=100]

    # Exact C8 audit.
    C8={Fraction(1,13),Fraction(3,13),Fraction(4,13),Fraction(5,11),
        Fraction(6,11),Fraction(9,13),Fraction(10,13),Fraction(12,13)}
    assert C8<=state_set
    c8_edges=[]
    for x in sorted(C8):
        for act,y in children(x):
            status="inside" if y in C8 else "terminal" if y in TERMINAL else "OUTSIDE"
            assert status!="OUTSIDE"
            c8_edges.append({"state":str(x),"action":act,"successor":str(y),"status":status})
    c8_max_q=max(Fraction(x.denominator,x.denominator-x.numerator) for x in C8)
    assert c8_max_q==13

    # Closed SCC table.
    rows=[]
    for idx,i in enumerate(sorted(closed_scc,key=lambda j:(len(sccs[j]),sorted(str(x) for x in sccs[j]))),1):
        C=sccs[i]
        rows.append({
            "closed_scc_id":idx,
            "size":len(C),
            "states":";".join(str(x) for x in sorted(C)),
            "denominators":";".join(map(str,sorted({x.denominator for x in C}))),
            "max_q":str(max(Fraction(x.denominator,x.denominator-x.numerator) for x in C)),
            "orders_10":";".join(f"{q}:{multiplicative_order(10,q)}" for q in sorted({x.denominator for x in C}) if gcd(q,10)==1),
        })
    with (OUTDIR/"rgphi_trap_closed_sccs_D500.csv").open("w",newline="") as f:
        w=csv.DictWriter(f,fieldnames=rows[0].keys());w.writeheader();w.writerows(rows)

    crows=[]
    for idx,C in enumerate(small_closures,1):
        crows.append({
            "closure_id":idx,
            "size":len(C),
            "states":";".join(str(x) for x in sorted(C)),
            "generator_scc_count":len(closure_map[C]),
            "max_q":str(max(Fraction(x.denominator,x.denominator-x.numerator) for x in C)),
            "contains_C8":C8<=C,
            "equals_C8":C==C8,
        })
    with (OUTDIR/"rgphi_trap_forward_closures_D500.csv").open("w",newline="") as f:
        w=csv.DictWriter(f,fieldnames=crows[0].keys());w.writeheader();w.writerows(crows)

    with (OUTDIR/"rgphi_C8_exact_audit.csv").open("w",newline="") as f:
        w=csv.DictWriter(f,fieldnames=c8_edges[0].keys());w.writeheader();w.writerows(c8_edges)

    result={
        "status":"PASS",
        "base":BASE,
        "denominator_bound":D,
        "nonterminal_states_enumerated":len(states),
        "directed_nonterminal_edges":G.number_of_edges(),
        "strongly_connected_components":len(sccs),
        "closed_sccs_modulo_terminal_set":len(closed_scc),
        "exact_finite_forward_closures":len(closures),
        "small_forward_closures_size_le_100":len(small_closures),
        "C8":{
            "certified_forward_invariant_modulo_terminals":True,
            "size":8,
            "max_q":"13",
            "denominators":[11,13],
            "ord_13_10":multiplicative_order(10,13),
            "ord_11_10":multiplicative_order(10,11),
            "present_as_exact_closure":frozenset(C8) in closure_map,
        },
        "boundary":"Atlas is complete only for traps whose nonterminal successors all remain within denominator <=500.",
    }
    (OUTDIR/"rgphi_trap_atlas_result_D500.json").write_text(json.dumps(result,indent=2),encoding="utf-8")
    print(json.dumps(result,indent=2))


if __name__=="__main__":
    main()
