#!/usr/bin/env python3
"""Small deterministic layout, exactness and literature fixes after generation."""
from pathlib import Path

# This script is intentionally idempotent and safe to rerun after governance edits.
ROOT = Path(__file__).resolve().parents[2]
TEX = ROOT / "paper" / "main.tex"

text = TEX.read_text(encoding="utf-8")

text = text.replace(
    "\\begin{tikzpicture}[\n  box/.style={draw, rounded corners, align=center, inner sep=4pt,\n              font=\\small, text width=.29\\textwidth},\n  wide/.style={box, text width=.66\\textwidth},",
    "\\begin{tikzpicture}[scale=.82, transform shape,\n  box/.style={draw, rounded corners, align=center, inner sep=4pt,\n              font=\\small, text width=.25\\textwidth},\n  wide/.style={box, text width=.58\\textwidth},",
)
text = text.replace("below left=5mm and 5mm of layers", "below left=5mm and 2mm of layers")
text = text.replace("below right=5mm and 5mm of layers", "below right=5mm and 2mm of layers")
text = text.replace(
    "The public research repository is available at \\url{https://github.com/FacundoFirmenich/rgphi-radix-mobius-dynamics}.",
    "The public research repository is available as the \\href{https://github.com/FacundoFirmenich/rgphi-radix-mobius-dynamics}{RG$\\Phi$ project repository}.",
)

old_corollary = r"""\begin{corollary}[Current height is not a Bellman value]
The scalar $q(x)$ cannot order states by future portal value.  At the relevant checkpoints, future-winning latent states have heights approximately $4.68$, $2.55$, and $2.14$, while the target-optimal competitors have heights $129$, $1203$, and above $11{,}000$.
\end{corollary}"""
new_corollary = r"""\begin{corollary}[Current height is not a Bellman value]
The scalar $q(x)$ cannot order states by future portal value.  The following exact same-time comparisons reverse the ordering induced by present height:
\begin{center}
\small
\begin{tabular}{ccllc}
\toprule
checkpoint & target-optimal state & $q$ & latent winning state ($q$) & remaining costs\\
\midrule
$45$  & $128/129$     & $129$   & $103/131\ (131/28)$        & $42>40$\\
$85$  & $1202/1203$   & $1203$  & $956/1573\ (1573/617)$     & $54>35$\\
$120$ & $11156/11157$ & $11157$ & $11803/22160\ (22160/10357)$ & $48>42$\\
\bottomrule
\end{tabular}
\end{center}
Thus states of much smaller current height can have strictly smaller exact cost to the next portal.
\end{corollary}"""
text = text.replace(old_corollary, new_corollary)

if "Peng2014Hitting" not in text:
    literature_anchor = (
        "The need for sufficient state in dynamic programming is classical \\cite{Bellman1952On,Light2023The}; automata-based state augmentation for non-Markovian objectives appears, for example, in \\cite{Brafman2017Specifying}.  Likewise, invariant or survivor sets in open expanding systems are established objects \\cite{Kong2025Open}, and independently checkable certificates are an active topic in formal reachability verification \\cite{Chatterjee2025Fixed}.  We therefore do not claim novelty for radix dynamics, projective/Farey methods, state augmentation, trapping, or certification as general concepts."
    )
    literature_expanded = literature_anchor + (
        "  Quantitative hitting depth for the Gauss map has also been studied in an asymptotic metric setting \\cite{Peng2014Hitting}; that notion concerns cylinder approximation along typical irrational orbits, rather than exact finite target optimization over a controlled rational semigroup.  Recent work on a rational-function tree generated by inverse branches of generalized Farey maps \\cite{LangeveldRalston2026Tree} is structurally adjacent, but studies enumeration and pole geometry rather than nonnested extremal first-hit states."
    )
    if literature_anchor not in text:
        raise RuntimeError("literature paragraph anchor not found")
    text = text.replace(literature_anchor, literature_expanded, 1)

    bibliography_anchor = r"""\bibitem{Silverman2007The}
J. H. Silverman,
\emph{The Arithmetic of Dynamical Systems},
Graduate Texts in Mathematics 241, Springer, 2007."""
    new_bibliography = r"""\bibitem{Peng2014Hitting}
L. Peng,
\emph{On the hitting depth in the dynamical system of continued fractions},
Chaos Solitons Fractals 69 (2014), 22--30,
doi:10.1016/j.chaos.2014.09.003.

\bibitem{LangeveldRalston2026Tree}
N. Langeveld and D. Ralston,
\emph{On a tree of rational functions related to continued fractions},
Indag. Math. (N.S.) (2026),
doi:10.1016/j.indag.2026.06.001; arXiv:2512.11595.

""" + bibliography_anchor
    if bibliography_anchor not in text:
        raise RuntimeError("bibliography anchor not found")
    text = text.replace(bibliography_anchor, new_bibliography, 1)

TEX.write_text(text, encoding="utf-8")
print("PASS_PAPER_I_FINALIZATION_POSTFIX")
